import "dotenv/config";
import { Pool } from "pg";

export const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
});

export async function initDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id UUID PRIMARY KEY,
      name VARCHAR(100) NOT NULL,
      email VARCHAR(255) NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      role VARCHAR(20) NOT NULL DEFAULT 'user',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      CONSTRAINT users_role_check CHECK (role IN ('user', 'admin', 'superadmin'))
    );
  `);

  await pool.query(`
    ALTER TABLE users
    DROP CONSTRAINT IF EXISTS users_role_check;
  `);

  await pool.query(`
    ALTER TABLE users
    ADD CONSTRAINT users_role_check
    CHECK (role IN ('user', 'admin', 'superadmin'));
  `);

  await pool.query(`
    ALTER TABLE users
    ADD COLUMN IF NOT EXISTS approval_status VARCHAR(20) NOT NULL DEFAULT 'pending';
  `);

  await pool.query(`
    UPDATE users
    SET approval_status = 'approved'
    WHERE role IN ('admin', 'superadmin') AND approval_status = 'pending';
  `);

  await pool.query(`
    ALTER TABLE users
    DROP CONSTRAINT IF EXISTS users_approval_status_check;
  `);

  await pool.query(`
    ALTER TABLE users
    ADD CONSTRAINT users_approval_status_check
    CHECK (approval_status IN ('pending', 'approved'));
  `);

  if (process.env.BOOTSTRAP_SUPERADMIN_EMAIL) {
    const existingSuperadmin = await pool.query(
      "SELECT 1 FROM users WHERE role = 'superadmin' LIMIT 1",
    );
    if (existingSuperadmin.rowCount === 0) {
      const result = await pool.query(
        `UPDATE users
         SET role = 'superadmin', approval_status = 'approved', updated_at = NOW()
         WHERE email = $1
         RETURNING id`,
        [process.env.BOOTSTRAP_SUPERADMIN_EMAIL.trim().toLowerCase()],
      );
      if (result.rowCount === 0) {
        console.warn(
          "BOOTSTRAP_SUPERADMIN_EMAIL did not match an existing user account.",
        );
      }
    }
  }

  await pool.query(`
    CREATE TABLE IF NOT EXISTS student_attendance (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(150) NOT NULL,
      course VARCHAR(100) NOT NULL,
      "session" VARCHAR(150),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS staff_attendance (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(150) NOT NULL,
      course VARCHAR(100),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  await pool.query(`
    ALTER TABLE staff_attendance
    ADD COLUMN IF NOT EXISTS course VARCHAR(100);
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS students (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(150) NOT NULL,
      email VARCHAR(255),
      phone VARCHAR(50),
      course VARCHAR(100) NOT NULL,
      status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS staff (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(150) NOT NULL,
      email VARCHAR(255),
      phone VARCHAR(50),
      status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS receipts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT NOT NULL REFERENCES students(id),
      student_name VARCHAR(150) NOT NULL,
      course VARCHAR(100) NOT NULL,
      amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
      purpose VARCHAR(200) NOT NULL,
      payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);
}
