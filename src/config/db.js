import "dotenv/config";
import { Pool } from "pg";
import { logger } from "../utils/logger.js";

export const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
});

pool.on("error", (error) => {
  logger.error("database.idle_client_error", error);
});

export async function initDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id UUID PRIMARY KEY,
      name VARCHAR(100) NOT NULL,
      email VARCHAR(255) NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      role VARCHAR(20),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  await pool.query(`
    ALTER TABLE users
    DROP CONSTRAINT IF EXISTS users_role_check;
  `);

  await pool.query(`
    ALTER TABLE users
    ALTER COLUMN role DROP DEFAULT,
    ALTER COLUMN role DROP NOT NULL;
  `);

  await pool.query(`
    UPDATE users
    SET role = NULL
    WHERE role = 'user';
  `);

  await pool.query(`
    ALTER TABLE users
    ADD CONSTRAINT users_role_check
    CHECK (role IS NULL OR role IN ('admin', 'superadmin'));
  `);

  const approvalStatusColumn = await pool.query(
    `SELECT 1
     FROM information_schema.columns
     WHERE table_schema = current_schema()
       AND table_name = 'users'
       AND column_name = 'approval_status'`,
  );

  await pool.query(`
    ALTER TABLE users
    ADD COLUMN IF NOT EXISTS approval_status VARCHAR(20) NOT NULL DEFAULT 'pending';
  `);

  if (approvalStatusColumn.rowCount === 0) {
    await pool.query(`
      UPDATE users
      SET approval_status = 'approved'
      WHERE role IN ('admin', 'superadmin');
    `);
  }

  await pool.query(`
    ALTER TABLE users
    DROP CONSTRAINT IF EXISTS users_approval_status_check;
  `);

  await pool.query(`
    ALTER TABLE users
    ADD CONSTRAINT users_approval_status_check
    CHECK (approval_status IN ('pending', 'approved'));
  `);

  if (process.env.BOOTSTRAP_SUPERADMIN_EMAIL) {
    const existingSuperadmin = await pool.query(
      `SELECT 1
       FROM users
       WHERE role = 'superadmin' AND approval_status = 'approved'
       LIMIT 1`,
    );
    if (existingSuperadmin.rowCount === 0) {
      const result = await pool.query(
        `UPDATE users
         SET role = 'superadmin', approval_status = 'approved', updated_at = NOW()
         WHERE email = $1
         RETURNING id`,
        [process.env.BOOTSTRAP_SUPERADMIN_EMAIL.trim().toLowerCase()],
      );
      if (result.rowCount === 0) {
        logger.warn(
          "database.bootstrap_superadmin_not_found",
          { email: process.env.BOOTSTRAP_SUPERADMIN_EMAIL.trim().toLowerCase() },
        );
      }
    }
  }

  await pool.query(`
    CREATE TABLE IF NOT EXISTS student_attendance (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(150) NOT NULL,
      course VARCHAR(100) NOT NULL,
      "session" VARCHAR(150),
      student_number VARCHAR(20),
      attendance_date DATE NOT NULL DEFAULT CURRENT_DATE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS staff_attendance (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(150) NOT NULL,
      course VARCHAR(100),
      staff_number VARCHAR(20),
      attendance_date DATE NOT NULL DEFAULT CURRENT_DATE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  await pool.query(`
    ALTER TABLE staff_attendance
    ADD COLUMN IF NOT EXISTS course VARCHAR(100);
  `);

  await pool.query(`
    ALTER TABLE student_attendance
    ADD COLUMN IF NOT EXISTS student_number VARCHAR(20);
  `);

  await pool.query(`
    ALTER TABLE student_attendance
    ADD COLUMN IF NOT EXISTS attendance_date DATE;
  `);

  await pool.query(`
    ALTER TABLE staff_attendance
    ADD COLUMN IF NOT EXISTS staff_number VARCHAR(20);
  `);

  await pool.query(`
    ALTER TABLE staff_attendance
    ADD COLUMN IF NOT EXISTS attendance_date DATE;
  `);

  await pool.query(`
    UPDATE student_attendance
    SET attendance_date = created_at::date
    WHERE attendance_date IS NULL;
  `);

  await pool.query(`
    UPDATE staff_attendance
    SET attendance_date = created_at::date
    WHERE attendance_date IS NULL;
  `);

  await pool.query(`
    ALTER TABLE student_attendance
    ALTER COLUMN attendance_date SET DEFAULT CURRENT_DATE,
    ALTER COLUMN attendance_date SET NOT NULL;
  `);

  await pool.query(`
    ALTER TABLE staff_attendance
    ALTER COLUMN attendance_date SET DEFAULT CURRENT_DATE,
    ALTER COLUMN attendance_date SET NOT NULL;
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS student_attendance_number_date_idx
    ON student_attendance (UPPER(BTRIM(student_number)), attendance_date)
    WHERE student_number IS NOT NULL;
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS staff_attendance_number_date_idx
    ON staff_attendance (UPPER(BTRIM(staff_number)), attendance_date)
    WHERE staff_number IS NOT NULL;
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS attendance_daily_claims (
      kind CHAR(1) NOT NULL CHECK (kind IN ('S', 'E')),
      identifier VARCHAR(20) NOT NULL,
      attendance_date DATE NOT NULL,
      PRIMARY KEY (kind, identifier, attendance_date)
    );
  `);

  await pool.query(`
    INSERT INTO attendance_daily_claims (kind, identifier, attendance_date)
    SELECT 'S', UPPER(BTRIM(student_number)), attendance_date
    FROM student_attendance
    WHERE student_number IS NOT NULL
    ON CONFLICT DO NOTHING;
  `);

  await pool.query(`
    INSERT INTO attendance_daily_claims (kind, identifier, attendance_date)
    SELECT 'E', UPPER(BTRIM(staff_number)), attendance_date
    FROM staff_attendance
    WHERE staff_number IS NOT NULL
    ON CONFLICT DO NOTHING;
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS students (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(150) NOT NULL,
      email VARCHAR(255),
      course VARCHAR(100) NOT NULL,
      status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS staff (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(150) NOT NULL,
      email VARCHAR(255),
      status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  await pool.query(`
    ALTER TABLE staff
    ADD COLUMN IF NOT EXISTS roles TEXT[] NOT NULL DEFAULT '{}';
  `);

  await pool.query(`
    ALTER TABLE students
    ADD COLUMN IF NOT EXISTS student_number VARCHAR(20);
  `);

  await pool.query(`
    ALTER TABLE staff
    ADD COLUMN IF NOT EXISTS staff_number VARCHAR(20);
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS directory_id_counters (
      kind CHAR(1) NOT NULL,
      year SMALLINT NOT NULL,
      last_value INTEGER NOT NULL,
      PRIMARY KEY (kind, year),
      CHECK (kind IN ('S', 'E'))
    );
  `);

  await pool.query(`
    UPDATE students
    SET student_number = 'S' || TO_CHAR(created_at, 'YY') || '/' ||
                         LPAD(id::text, GREATEST(3, LENGTH(id::text)), '0')
    WHERE student_number IS NULL;
  `);

  await pool.query(`
    UPDATE staff
    SET staff_number = 'E' || TO_CHAR(created_at, 'YY') || '/' ||
                       LPAD(id::text, GREATEST(3, LENGTH(id::text)), '0')
    WHERE staff_number IS NULL;
  `);

  await pool.query(`
    INSERT INTO directory_id_counters (kind, year, last_value)
    SELECT 'S', SUBSTRING(student_number, 2, 2)::smallint,
           MAX(SUBSTRING(student_number, 5)::integer)
    FROM students
    GROUP BY SUBSTRING(student_number, 2, 2)::smallint
    ON CONFLICT (kind, year)
    DO UPDATE SET last_value = GREATEST(directory_id_counters.last_value, EXCLUDED.last_value);
  `);

  await pool.query(`
    INSERT INTO directory_id_counters (kind, year, last_value)
    SELECT 'E', SUBSTRING(staff_number, 2, 2)::smallint,
           MAX(SUBSTRING(staff_number, 5)::integer)
    FROM staff
    GROUP BY SUBSTRING(staff_number, 2, 2)::smallint
    ON CONFLICT (kind, year)
    DO UPDATE SET last_value = GREATEST(directory_id_counters.last_value, EXCLUDED.last_value);
  `);

  await pool.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS students_student_number_unique
    ON students (UPPER(student_number));
  `);

  await pool.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS staff_staff_number_unique
    ON staff (UPPER(staff_number));
  `);

  await pool.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS students_email_lower_unique
    ON students (LOWER(BTRIM(email)))
    WHERE email IS NOT NULL AND BTRIM(email) <> '';
  `);

  await pool.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS staff_email_lower_unique
    ON staff (LOWER(BTRIM(email)))
    WHERE email IS NOT NULL AND BTRIM(email) <> '';
  `);

  await pool.query(`
    ALTER TABLE students DROP COLUMN IF EXISTS phone;
  `);

  await pool.query(`
    ALTER TABLE staff DROP COLUMN IF EXISTS phone;
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS receipts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT REFERENCES students(id),
      student_name VARCHAR(150) NOT NULL,
      course VARCHAR(100) NOT NULL,
      amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
      purpose VARCHAR(200) NOT NULL,
      payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  await pool.query(`
    ALTER TABLE receipts
    ALTER COLUMN student_id DROP NOT NULL;
  `);

  await pool.query(`
    ALTER TABLE receipts
    ADD COLUMN IF NOT EXISTS receipt_number VARCHAR(50),
    ADD COLUMN IF NOT EXISTS payment_method VARCHAR(50),
    ADD COLUMN IF NOT EXISTS details JSONB NOT NULL DEFAULT '{}'::jsonb,
    ADD COLUMN IF NOT EXISTS image_url TEXT,
    ADD COLUMN IF NOT EXISTS image_public_id TEXT;
  `);
}
